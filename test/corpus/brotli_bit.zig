pub fn brotli_mask_bits(val: i64, n: i64) i64 {
    var mask: i64 = 0;

  mask = (_lia_shl(1, n) - 1) & 4294967295;
  return (val & mask);

}

pub fn brotli_fill_byte(val: i64, new_byte: i64, bits_in: i64) i64 {
    var b: i64 = 0;
    var shifted: i64 = 0;

  b = new_byte & 255;
  shifted = _lia_shl(b, bits_in) & 4294967295;
  return (val | shifted);

}

pub fn brotli_drop_bits(val: i64, n: i64) i64 {

  return (_lia_ushr(val, n));

}

