pub fn lk_gcd(a_in: i64, b_in: i64) i64 {
    var a: i64 = 0;
    var b: i64 = 0;
    var r: i64 = 0;
    var t: i64 = 0;

  a = a_in & 4294967295;
  b = b_in & 4294967295;
  if (a == 0) { return b ;}
  if (b == 0) { return a ;}

  r = 0;
  while (((a | b) & 1) == 0) {
    a = _lia_shr(a, 1);
    b = _lia_shr(b, 1);
    r = r + 1;
  }

  while ((a & 1) == 0) {
    a = _lia_shr(a, 1);
  }

  while (b != 0) {
    while ((b & 1) == 0) {
      b = _lia_shr(b, 1);
    }
    if (a > b) {
      t = b;
      b = a;
      a = t;
    }
    b = b - a;
  }

  return (_lia_shl(a, r)) & 4294967295;

}

pub fn lk_int_sqrt(x_in: i64) i64 {
    var x: i64 = 0;
    var b: i64 = 0;
    var m: i64 = 0;
    var y: i64 = 0;

  x = x_in & 4294967295;
  if (x <= 1) { return x ;}

  b = 0;
  m = 1073741824;
  y = 0;

  while (m > x) {
    m = _lia_shr(m, 2);
  }

  while (m != 0) {
    b = y + m;
    y = _lia_shr(y, 1);
    if (x >= b) {
      x = x - b;
      y = y + m;
    }
    m = _lia_shr(m, 2);
  }

  return y & 4294967295;

}

pub fn lk_hweight32(w_in: i64) i64 {
    var w: i64 = 0;
    var res: i64 = 0;

  w = w_in & 4294967295;
  res = (w - ((_lia_shr(w, 1)) & 1431655765)) & 4294967295;
  res = ((res & 858993459) + ((_lia_shr(res, 2)) & 858993459)) & 4294967295;
  res = (res + (_lia_shr(res, 4))) & 252645135;
  res = (res + (_lia_shr(res, 8))) & 4294967295;
  return (res + (_lia_shr(res, 16))) & 255;

}

pub fn lk_fls(x_in: i64) i64 {
    var x: i64 = 0;
    var r: i64 = 0;

  x = x_in & 4294967295;
  if (x == 0) { return 0 ;}
  r = 32;
  if ((x & 4294901760) == 0) {
    x = _lia_shl(x, 16);
    r = r - 16;
  }
  if ((x & 4278190080) == 0) {
    x = _lia_shl(x, 8);
    r = r - 8;
  }
  if ((x & 4026531840) == 0) {
    x = _lia_shl(x, 4);
    r = r - 4;
  }
  if ((x & 3221225472) == 0) {
