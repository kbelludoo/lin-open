pub fn lin_opt_fls(x_in: i64) i64 {
    var x: i64 = 0;

  x = x_in & 4294967295;
  if (x == 0) { return 0 ;}
  x = x | _lia_shr(x, 1);
  x = x | _lia_shr(x, 2);
  x = x | _lia_shr(x, 4);
  x = x | _lia_shr(x, 8);
  x = x | _lia_shr(x, 16);
  return lk_hweight32(x);

}

pub fn lin_opt_gcd(a_in: i64, b_in: i64) i64 {
    var a: i64 = 0;
    var b: i64 = 0;
    var common_zeros: i64 = 0;
    var t: i64 = 0;

  a = a_in & 4294967295;
  b = b_in & 4294967295;
  if (a == 0) { return b ;}
  if (b == 0) { return a ;}

  // Fast common power of 2 elimination
  common_zeros = 0;
  while (((a | b) & 15) == 0) {
    a = _lia_shr(a, 4);
    b = _lia_shr(b, 4);
    common_zeros = common_zeros + 4;
  }
  while (((a | b) & 1) == 0) {
    a = _lia_shr(a, 1);
    b = _lia_shr(b, 1);
    common_zeros = common_zeros + 1;
  }

  while ((a & 15) == 0) { a = _lia_shr(a, 4); }
  while ((a & 1) == 0) { a = _lia_shr(a, 1); }

  while (b != 0) {
    while ((b & 15) == 0) { b = _lia_shr(b, 4); }
    while ((b & 1) == 0) { b = _lia_shr(b, 1); }
    if (a > b) {
      t = b;
      b = a;
      a = t;
    }
    b = b - a;
  }

  return (_lia_shl(a, common_zeros)) & 4294967295;

}

