function pyMatch(out, st, indent, prog) {
  void prog;
  const pad = '    '.repeat(indent);
  const target = pyExprRaw(st.target);
  for (let idx = 0; idx < st.arms.length; idx++) {
    const arm = st.arms[idx];
    const condTxt = pyArmCond(target, arm.pat, arm.guard);
    const kw = idx === 0 ? 'if' : 'elif';
    out.push(`${pad}${kw} ${condTxt}:`);
    pushBlock(out, pyStmts(arm.body, indent + 1), pad);
  }
}

function pyArmCond(target, pat, guard) {
  if (pat === '_') return guard ? `(${guard})` : 'True';
  const enumMatch = pat.match(/^([A-Za-z_$][\w$]*)\(([^)]+)\)$/);
  const tupleMatch = pat.match(/^\(([^)]+)\)$/);
  let base;
  if (enumMatch) {
    const tag = enumMatch[1];
    const v = safeEmitId(enumMatch[2].trim());
    base = `getattr(${target}, 'tag', None) == '${tag}'`;
    base += ` # binds ${v}`;
  } else if (tupleMatch) {
    base = `isinstance(${target}, (list, tuple)) and len(${target}) >= ${tupleMatch[1].split(',').length}`;
  } else {
    base = `${target} == ${pat}`;
  }
  if (guard) base += ` and (${guard})`;
  return base;
}

export function emitGo(prog, opts = {}) {
  const fnLines = [];
  for (const fn of prog.fns) {
    if (opts.__stubNames && opts.__stubNames.has(fn.name)) {
      fnLines.push(`func ${safeEmitId(snakeCase(fn.name))}(...interface{}) interface{} { panic("${fn.name}: js_runtime_only") }`);
      continue;
    }
    emitGoFn(fnLines, fn);
  }
  const lines = ['// generated by lin-rewrite → go'];
  lines.push('package main');
  const bodyText = fnLines.join('\n');
  const needsMath = /\bmath\.Abs\b|\bmath\.Floor\b/.test(bodyText);
  const needsFmt = true;
  lines.push('');
  lines.push('import (');
  if (needsFmt) lines.push('\t"fmt"');
  if (needsMath) lines.push('\t"math"');
  lines.push(')');
  lines.push('');
  lines.push(...fnLines);
  void opts;
  return lines.join('\n');
}

function goType(t) {
  if (t === '@str') return 'string';
  if (t === '@bool') return 'bool';
  switch (t) {
    case 'int': return 'int';
    case 'float': return 'float64';
    case 'string': return 'string';
    case 'bool': return 'bool';
    default: return 'interface{}';
  }
}

function zeroFor(t) {
  switch (goType(t)) {
    case 'int': return '0';
    case 'float64': return '0.0';
    case 'string': return '""';
    case 'bool': return 'false';
    default: return 'nil';
  }
}

function emitGoFn(lines, fn, opts) {
  prepareNativeFn(fn);
  const strP = new Set(strParamNames(fn));
  const ps = paramList(fn);
  for (const p of ps) if (strP.has(p.name)) p.type = '@str';
  const sig = ps.map((p) => `${safeEmitId(p.name)} ${goType(p.type)}`).join(', ');
  const retTypes = fn.returnType ? goType(normType(fn.returnType.replace(/^[^A-Za-z]+/, ''))) : (retIsBool(fn) ? 'bool' : 'interface{}');
  lines.push(`func ${safeEmitId(snakeCase(fn.name))}(${sig}) ${retTypes} {`);
  for (const p of ps) {
    if (p.def != null && p.def !== '' && goType(p.type) === 'interface{}') {
      lines.push(`\tif ${safeEmitId(p.name)} == nil { ${safeEmitId(p.name)} = ${p.def} }`);
    }
  }
  const locals = new Set();
  for (const st of fn.body) collectLocalsGo(st, locals, ps.map((p) => p.name));
  const lt = 'int';
  for (const l of locals) {
    lines.push(`\tvar ${safeEmitId(l)} ${lt}`);
  }
  lines.push(goStmts(fn.body, 1));
  lines.push('}');
  lines.push('');
}

function collectLocalsGo(st, locals, params) {
  const add = (id) => {
    if (!params.includes(id) && !['return', 'if', 'for', 'else'].includes(id)) locals.add(id);
  };
  if (st.type === 'assign' && /^[A-Za-z_$][\w$]*$/.test(st.idPath)) add(st.idPath);
  for (const key of ['then', 'else', 'body']) {
    if (Array.isArray(st[key])) for (const s2 of st[key]) collectLocalsGo(s2, locals, params);
  }
  if (Array.isArray(st.elseIf)) {
    for (const ei of st.elseIf) {
      for (const s2 of ei.body) collectLocalsGo(s2, locals, params);
      let tail = ei.chainTail;
      while (tail) {
        for (const s2 of tail.body) collectLocalsGo(s2, locals, params);
        tail = tail.chainTail;
      }
    }
  }
}

function goIndent(depth) {
  return '\t'.repeat(depth);
}

function goStmts(stmts, depth) {
  const out = [];
  const pad = goIndent(depth);
  for (const st of stmts) {
    switch (st.type) {
      case 'return':
        out.push(`${pad}return ${goExpr(goExprRaw(st.expr))}`);
        break;
      case 'throw':
        out.push(`${pad}panic(${goExpr(goExprRaw(st.expr))})`);
        break;
      case 'break':
        out.push(`${pad}break`);
        break;
      case 'continue':
        out.push(`${pad}continue`);
        break;
      case 'assign':
        out.push(`${pad}${safeEmitId(st.idPath)} ${st.op} ${stripDeclKw(goExpr(goExprRaw(st.rhs)))}`);
        break;
      case 'expr':
        out.push(`${pad}_ = ${stripDeclKw(goExpr(goExprRaw(st.expr)))}`);
        break;
      case 'if': {
        out.push(`${pad}if (${goExpr(goExprRaw(st.cond))}) {`);
        out.push(goStmts(st.then, depth + 1));
        let closed = false;
        for (const ei of st.elseIf || []) {
          out.push(`${pad}} else if (${goExpr(goExprRaw(ei.cond))}) {`);
          out.push(goStmts(collectChainBodies(ei), depth + 1));
          closed = true;
        }
        void closed;
        if (st.else) {
          out.push(`${pad}} else {`);
          out.push(goStmts(normalizeElse(st.else), depth + 1));
        }
        out.push(`${pad}}`);
        break;
      }
      case 'for': {
        const initM = st.init.match(/^([A-Za-z_$][\w$]*)\s*=\s*([\s\S]+)$/);
        const stepM = st.step.match(/^([A-Za-z_$][\w$]*)\s*(\+\+|--)$/);
        const initPart = initM ? `${safeEmitId(initM[1])} := ${goExpr(initM[2])}; ` : '';
        const condPart = `(${goExpr(goExprRaw(st.cond))})`;
        const stepPart = stepM ? `; ${stepM[1]} ${stepM[2] === '++' ? '+=' : '-='} 1` : `; ${goExpr(st.step)}`;
        out.push(`${pad}for ${initPart}${condPart}${stepPart} {`);
        out.push(goStmts(st.body, depth + 1));
        out.push(`${pad}}`);
        break;
      }
      case 'while':
        out.push(`${pad}for (${goExpr(goExprRaw(st.cond))}) {`);
        out.push(goStmts(st.body, depth + 1));
        out.push(`${pad}}`);
        break;
      case 'match': {
        const target = goExpr(goExprRaw(st.target));
        for (let idx = 0; idx < st.arms.length; idx++) {
          const arm = st.arms[idx];
          const cond = goArmCond(target, arm.pat, arm.guard);
          const kw = idx === 0 ? 'if' : '} else if';
          if (idx === 0) out.push(`${pad}if ${cond} {`);
          else out.push(`${pad}${kw} ${cond} {`);
          out.push(goStmts(arm.body, depth + 1));
        }
        out.push(`${pad}}`);
        break;
      }
      default:
        throw new EmitUnsupportedError(`go stmt ${st.type}`);
    }
  }
  return out.join('\n');
}

function goArmCond(target, pat, guard) {
  if (pat === '_') return guard ? guard : 'true';
  const tupleMatch = pat.match(/^\(([^)]+)\)$/);
  let base;
  if (tupleMatch) {
    base = `isSlice(${target}) && sliceLen(${target}) >= ${tupleMatch[1].split(',').length}`;
  } else {
    base = `eqAny(${target}, ${pat})`;
  }
  if (guard) base += ` && (${guard})`;
  return base;
}

export function goExprRaw(expr) {
  return expr && expr.parts
    ? expr.parts.map((p) => (p.kind === 'raw' ? p.text : goInline(p.node))).join(' ')
    : String(expr ?? '');
}

function goInline(node) {
  throw new EmitUnsupportedError(`go inline ${node.kind}`);
}

export function goExpr(text) {
  let s = String(text);
  s = s.replace(/([A-Za-z_$][\w$]*)\.charCodeAt\(([^()]*)\)/g, 'int($1[$2])');
  s = s.replace(/([A-Za-z_$][\w$]*)\.length\b/g, 'len($1)');
  s = s.replace(/String\(([A-Za-z_$][\w$]*)\)/g, '$1');
  s = s.replace(/\btypeof\s+([A-Za-z_$][\w$]*)/g, 'goTypeOf($1)');
  s = s.replace(/\bundefined\b|\bnull\b/g, 'nil');
  s = s.replace(/\btrue\b/g, 'true').replace(/\bfalse\b/g, 'false');
  s = s.replace(/\bMath\.abs\(/g, 'math.Abs(');
  s = s.replace(/\bMath\.floor\(/g, 'math.Floor(');
  s = s.replace(/===/g, '==').replace(/!==/g, '!=');
  s = s.replace(/\s*&&\s*/g, ' && ').replace(/\s*\|\|\s*/g, ' || ');
  s = s.replace(/!(?=[A-Za-z_(])/g, '!');
  s = s.replace(/\?/g, '');
  return s;
}

export function emitRust(prog, opts = {}) {
  const lines = ['// generated by lin-rewrite → rust'];
  lines.push('#![allow(dead_code, unused_variables, unused_mut)]');
  lines.push('');
  for (const fn of prog.fns) {
    if (opts.__stubNames && opts.__stubNames.has(fn.name)) {
      lines.push(`pub fn ${snakeCaseRust(fn.name)}() -> i64 { panic!("${fn.name}: js_runtime_only"); }`);
      continue;
    }
    emitRustFn(lines, fn);
  }
  void opts;
  return lines.join('\n');
}

function rustType(t) {
  if (t === '@str') return '&str';
  if (t === '@bool') return 'bool';
  switch (normType(t)) {
    case 'int': return 'i64';
    case 'float': return 'f64';
    case 'string': return 'String';
    case 'bool': return 'bool';
    default: return 'i64';
  }
}

function rustZero(t) {
  switch (rustType(t)) {
    case 'i64': return '0';
    case 'f64': return '0.0';
    case 'String': return 'String::new()';
    case 'bool': return 'false';
    default: return '0';
  }
}

function emitRustFn(lines, fn) {
  prepareNativeFn(fn);
  const strP = new Set(strParamNames(fn));
  const isBool = retIsBool(fn);
  const ps = paramList(fn);
  if (ps.some((p) => !p.type)) {
    for (const p of ps) {
      if (!p.type) p.type = strP.has(p.name) ? '@str' : inferRustParamType({ ...fn, rawBody: stmtsText(fn), __bodyText: null, body: fn.body }, p.name);
      if (!p.type || p.type === 'int') {
        const t2 = stmtsText(fn);
        if (new RegExp(`\\b${p.name}\\.len\\(|\\bas_bytes`).test('')) {}
      }
    }
  } else {
    for (const p of ps) if (strP.has(p.name)) p.type = '@str';
  }
  if (!fn.returnType && isBool) fn.__forceBoolRet = true;
  const reassigned = new Set();
  const walkAssignsRust = (stmts) => {
    for (const st of stmts) {
      if (st.type === 'assign' && /^[A-Za-z_$][\w$]*$/.test(st.idPath)) reassigned.add(st.idPath);
      for (const key of ['then', 'else', 'body']) {
        if (Array.isArray(st[key])) walkAssignsRust(st[key], reassigned);
      }
      if (Array.isArray(st.elseIf)) for (const ei of st.elseIf) walkAssignsRust(ei.body, reassigned);
    }
  };
  walkAssignsRust(fn.body, reassigned);
  const strCount = ps.filter((p) => rustType(p.type) === '&str').length;
  const lifetime = strCount >= 2 ? "<'a>" : '';
  const lt = strCount >= 2 ? "'a " : '';
  const sig = ps.map((p) => `${reassigned.has(p.name) ? 'mut ' : ''}${safeEmitId(p.name)}: ${rustType(p.type).replace('&str', "&'a str")}`).join(', ');
  const generics = lifetime;
  let retKw = fn.returnType ? rustType(fn.returnType.replace(/^[^A-Za-z]+/, '')) : null;
  if (!retKw && fn.__forceBoolRet) retKw = 'bool';
  if (!retKw) retKw = rustType(ps[0] ? ps[0].type : 'int');
  const ret = ` -> ${retKw}`;
  lines.push(`pub fn ${snakeCaseRust(fn.name)}${generics}(${sig})${ret} {`);
  const locals = new Set();
  for (const st of fn.body) collectLocalsGo(st, locals, ps.map((p) => p.name));
  if (locals.size) {
    lines.push(`    let mut ${[...locals].map(safeEmitId).join(' = ' + rustZero(ps[0] ? ps[0].type : 'int') + '; let mut ') } = ${rustZero(ps[0] ? ps[0].type : 'int')};`);
  }
  lines.push(rustStmts(fn.body, 1, fn));
  lines.push('}');
  lines.push('');
}

function snakeCaseRust(name) {
  return snakeCase(name);
}

function inferRustParamType(fn, name) {
  const text = stmtsText(fn);
  if (new RegExp(`\\b${name}\\b[^\\n]*\\.charCodeAt|\\.length`).test(text)) return 'string';
  return 'int';
}

function rustIndent(d) {
  return '    '.repeat(d);
}

function rustStmts(stmts, depth, fn) {
  void fn;
  const out = [];
  const pad = rustIndent(depth);
  for (const st of stmts) {
    switch (st.type) {
      case 'return':
        out.push(`${pad}return ${rustExpr(rustRaw(st.expr))};`);
        break;
      case 'throw':
        out.push(`${pad}panic!(${rustExpr(rustRaw(st.expr))});`);
        break;
      case 'break':
        out.push(`${pad}break;`);
        break;
      case 'continue':
        out.push(`${pad}continue;`);
        break;
      case 'assign':
        out.push(`${pad}${safeEmitId(st.idPath)} ${st.op === '=' ? '=' : rustCompound(st.op)} ${stripDeclKw(rustExpr(rustRaw(st.rhs)))};`);
        break;
      case 'expr':
        out.push(`${pad}${stripDeclKw(rustExpr(rustRaw(st.expr)))};`);
        break;
      case 'if': {
        out.push(`${pad}if ${rustExpr(rustRaw(st.cond))} {`);
        out.push(rustStmts(st.then, depth + 1, fn));
        for (const ei of st.elseIf || []) {
          out.push(`${pad}} else if ${rustExpr(rustRaw(ei.cond))} {`);
          out.push(rustStmts(collectChainBodies(ei), depth + 1, fn));
        }
        if (st.else) {
          out.push(`${pad}} else {`);
          out.push(rustStmts(normalizeElse(st.else), depth + 1, fn));
        }
        out.push(`${pad}}`);
        break;
      }
      case 'for': {
        const initM = st.init.match(/^([A-Za-z_$][\w$]*)\s*=\s*([\s\S]+)$/);
        const stepM = st.step.match(/^([A-Za-z_$][\w$]*)\s*(\+\+|--)$/);
        if (initM) out.push(`${pad}let mut ${safeEmitId(initM[1])} = ${rustExpr(initM[2])};`);
        out.push(`${pad}while ${rustExpr(rustRaw(st.cond))} {`);
        const inner = [];
        if (stepM) {
          inner.push(`${rustIndent(depth + 1)}${safeEmitId(stepM[1])} ${stepM[2] === '++' ? '+' : '-'}= 1;`);
        } else if (st.step.trim()) {
          inner.push(`${rustIndent(depth + 1)}${rustExpr(st.step)};`);
        }
        out.push(rustStmts(st.body, depth + 1, fn));
        out.push(...inner);
        out.push(`${pad}}`);
        break;
      }
      case 'while':
        out.push(`${pad}while ${rustExpr(rustRaw(st.cond))} {`);
        out.push(rustStmts(st.body, depth + 1, fn));
        out.push(`${pad}}`);
        break;
      case 'match':
        emitRustMatch(out, st, depth, fn);
        break;
      default:
        throw new EmitUnsupportedError(`rust stmt ${st.type}`);
    }
  }
  return out.join('\n');
}

function rustCompound(op) {
  if (op === '|=') return '|=';
  if (op === '&=') return '&=';
  if (op === '^=') return '^=';
  if (op === '+=') return '+=';
  if (op === '-=') return '-=';
  if (op === '*=') return '*=';
  if (op === '/=') return '/=';
  if (op === '%=') return '%=';
  return '=';
}

function emitRustMatch(out, st, depth, fn) {
  const pad = rustIndent(depth);
  const target = safeEmitId(rustRaw(st.target).trim());
  const allLiteral = st.arms.every((a) => /^[-\w"'().,\s|]+$/.test(a.pat) && !/[{}]/.test(a.pat));
  if (allLiteral) {
    out.push(`${pad}match ${target} {`);
    for (const arm of st.arms) {
      const pat = arm.pat === '_' ? '_'.replace('_', '_ =>'.slice(0, 1)) : arm.pat;
      const armPat = arm.pat === '_' ? '_ =>' : `${arm.pat} =>`;
      void pat;
      out.push(`${pad}    ${armPat} {`);
      const body = rustStmts(arm.body, depth + 2, fn);
      out.push(body);
      out.push(`${pad}    }`);
    }
    out.push(`${pad}}`);
    return;
  }
  for (let idx = 0; idx < st.arms.length; idx++) {
    const arm = st.arms[idx];
    const cond = rustArmCond(target, arm.pat, arm.guard);
    if (idx === 0) out.push(`${pad}if ${cond} {`);
    else out.push(`${pad}} else if ${cond} {`);
    out.push(rustStmts(arm.body, depth + 1, fn));
  }
  out.push(`${pad}}`);
}

function rustArmCond(target, pat, guard) {
  if (pat === '_') return guard ? guard : 'true';
  const enumMatch = pat.match(/^([A-Za-z_$][\w$]*)\(([^)]+)\)$/);
  let base;
  if (enumMatch) {
    const tag = enumMatch[1];
    const v = safeEmitId(enumMatch[2].trim());
    base = `matches_tag(&${target}, "${tag}") /* bind ${v} */`;
  } else {
    base = `${target} == ${pat}`;
  }
  if (guard) base += ` && (${guard})`;
  return base;
}

