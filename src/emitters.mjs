export class EmitUnsupportedError extends Error {
  constructor(message) {
    super(`LIN_EMIT_UNSUPPORTED: ${message}`);
    this.name = 'EmitUnsupportedError';
  }
}

const JS_RUNTIME_ONLY = /\b(Buffer|crypto|bufferAllocUnsafe|timingSafeEqual|process|Intl|arguments)\b|\bthis\.|\bthis\[|\bswitch\b|\bnew\s+Date\b|Object\.(setPrototypeOf|defineProperty|entries|create)/;

export function isJsRuntimeOnly(body) {
  return JS_RUNTIME_ONLY.test(String(body || ''));
}

export function stmtsText(fn) {
  if (fn.__bodyText) return fn.__bodyText;
  return typeof fn.rawBody === 'string' ? fn.rawBody : jsBody(fn.body || []);
}


function inlineStrAliases(text) {
  let out = String(text || '');
  const aliases = [];
  const re = /([A-Za-z_$][\w$]*)\s*=\s*String\(([A-Za-z_$][\w$]*)\)\s*;/g;
  let m;
  while ((m = re.exec(out)) !== null) {
    aliases.push([m[1], m[2]]);
  }
  for (const [alias, real] of aliases) {
    out = out.replace(new RegExp(`\\b${alias}\\b`, 'g'), real);
  }
  return { text: out, aliases };
}


function stripDeclKw(line) {
  return String(line).replace(/(^|[;{}])\s*(?:const|let|var)\s+/g, '$1');
}

function strParamNames(fn) {
  const text = stmtsText(fn);
  const out = [];
  for (const p of paramList(fn)) {
    if (new RegExp(`\\b${p.name}\\s*\\.\\s*(charCodeAt|length)\\b`).test(text) || new RegExp(`String\\(\\s*${p.name}\\s*\\)`).test(text)) {
      out.push(p.name);
    }
  }
  return out;
}

function retIsBool(fn) {
  const text = stmtsText(fn);
  const rets = text.match(/\breturn\s+([^;{}]+)/g) || [];
  if (!rets.length) return false;
  return rets.every((rr) => /[=!<>]==?|&&|\|\|/.test(rr));
}

function paramList(fn) {
  return (fn.params || []).map((p) => ({ name: p.name, type: normType(p.type), def: p.def }));
}

function normType(t) {
  const s = String(t || '').trim();
  if (!s) return 'any';
  if (/^(int|i32|i64|integer)$/.test(s)) return 'int';
  if (/^(float|f64|double|number)$/.test(s)) return 'float';
  if (/^(str|string)$/.test(s)) return 'string';
  if (/^bool(ean)?$/.test(s)) return 'bool';
  return 'any';
}

function defaultFor(t) {
  switch (t) {
    case 'int': return '0';
    case 'float': return '0.0';
    case 'bool': return 'false';
    case 'string': return '""';
    default: return null;
  }
}

export function emitTs(prog, opts = {}) {
  const parts = [`/* generated by lin-rewrite → ts */`];
  if (prog.consts) {
    parts.push(`const $K: Record<string, number> = { ${Object.entries(prog.consts).map(([k, v]) => `${JSON.stringify(k)}:${v}`).join(',')} };`);
  }
  const exported = new Set(prog.exports.map((e) => e.split(/\s+as\s+/)[0].trim()));
  for (const mod of prog.modules || []) {
    parts.push(`const ${mod.name}: Record<string, (...a: unknown[]) => unknown> = ${moduleObjTs(mod)};`);
  }
  for (const u of prog.uses || []) {
    for (const sym of u.symbols) parts.push(`const ${sym} = ${u.module}.${sym};`);
  }
  for (const fn of prog.fns) {
    const ps = (fn.params || []).map((p) => {
      const t = p.type && normType(p.type) !== 'any' ? mapTsType(normType(p.type)) : 'unknown';
      return `${safeEmitId(p.name)}${p.def != null && p.def !== '' ? `: ${t} = ${p.def}` : `: ${t}`}`;
    }).join(', ');
    const rt = fn.returnType ? `: ${mapTsType(normType(fn.returnType.replace(/^[^A-Za-z]+/, '')))}` : ': unknown';
    const kw = exported.has(fn.name) ? 'export function' : 'function';
    const bodyText = jsBody(fn.body);
    const paramsSet = new Set((fn.params || []).map((p) => p.name));
    const bareIds = collectBareStmtIds(bodyText);
    const cleaned = stripBareIdStmts(bodyText);
    const locals = [...new Set([...collectAssignedIds(cleaned), ...bareIds])].filter((id) => {
      if (paramsSet.has(id)) return false;
      if (bareIds.has(id)) return true;
      return !firstUseIsRead(cleaned, id);
    });
    parts.push(`${kw} ${fn.name}(${ps})${rt} {${locals.length ? `let ${locals.join(',')};` : ''}${bodyText}}`);
  }
  void opts;
  return parts.join('\n');
}

function mapTsType(t) {
  switch (t) {
    case 'int': case 'float': return 'number';
    case 'string': return 'string';
    case 'bool': return 'boolean';
    default: return 'unknown';
  }
}

function moduleObjTs(mod) {
  const fns = (mod.program.fns || []).map((fn) => `${fn.name}: (${(fn.params || []).map(() => 'a: unknown').join(',') || ''}) => unknown`);
  void fns;
  const body = (mod.program.fns || []).map((fn) => `${fn.name}: function(...a: unknown[]): unknown { return (${fn.name}_impl)(...a); }`);
  void body;
  const defs = (mod.program.fns || []).map((fn) => `function ${mod.name}_${fn.name}(...a: unknown[]): unknown { throw new Error('stub'); }`);
  void defs;
  return `{ ${(mod.program.fns || []).map((fn) => `${fn.name}: ${mod.name}_${fn.name}`).join(', ')} }`;
}

export function emitPy(prog, opts = {}) {
  const lines = ['# generated by lin-rewrite → py'];
  lines.push(PY_RUNTIME);
  if (prog.consts) {
    for (const [k, v] of Object.entries(prog.consts)) lines.push(`${safeEmitId(k)} = ${v}`);
    lines.push('$K = {' + Object.entries(prog.consts).map(([k]) => `${JSON.stringify(k)}: ${safeEmitId(k)}`).join(', ') + '}');
  }
  for (const u of prog.uses || []) {
    for (const sym of u.symbols) lines.push(`${sym} = ${u.module}.${sym}`);
  }
  for (const fn of prog.fns) {
    emitPyFn(lines, prog, fn);
  }
  void opts;
  return lines.join('\n');
}

function emitPyFn(lines, prog, fn) {
  prepareNativeFn(fn);
  const text = stmtsText(fn);
  if (prog.__stubNames && prog.__stubNames.has(fn.name)) {
    const ps0 = paramList(fn).map((x) => safeEmitId(x.name)).join(', ');
    lines.push(`def ${safeEmitId(snakeCase(fn.name))}(${ps0}):`);
    lines.push(`    raise NotImplementedError('${fn.name}: js_runtime_only')`);
    lines.push('');
    return;
  }
  const name = safeEmitId(snakeCase(fn.name));
  const ps = paramList(fn);
  const sig = ps.map((p) => {
    const id = safeEmitId(p.name);
    return p.def != null && p.def !== '' ? `${id}=${pyExpr(p.def)}` : id;
  }).join(', ');
  lines.push(`def ${name}(${sig}):`);
  if (isJsRuntimeOnly(text)) {
    lines.push(`    raise NotImplementedError('${fn.name}: js_runtime_only')`);
    return;
  }
  const bodyLines = pyStmts(fn.body, 1, prog);
  lines.push(...(bodyLines.length ? bodyLines : ['    pass']));
  lines.push('');
}

function pyStmts(stmts, indent, prog) {
  const pad = '    '.repeat(indent);
  const out = [];
  for (const st of stmts) {
    switch (st.type) {
      case 'return':
        out.push(`${pad}return ${pyStmtTail(st.expr, indent)}`);
        break;
      case 'throw':
        out.push(`${pad}raise Exception(${pyExpr(stripThrow(st.expr))})`);
        break;
      case 'break':
        out.push(`${pad}break`);
        break;
      case 'continue':
        out.push(`${pad}continue`);
        break;
      case 'assign':
        out.push(`${pad}${pyLhs(st.idPath)} ${pyAssignOp(st.op)} ${pyStmtRhs(st.rhs, indent)}`);
        break;
      case 'expr':
        out.push(`${pad}${stripDeclKw(pyStmtTail(st.expr, indent))}`);
        break;
      case 'assign':
        break;
      case 'if': {
        out.push(`${pad}if ${pyCond(st.cond)}:`);
        pushBlock(out, pyStmts(st.then, indent + 1, prog), pad);
        for (const ei of st.elseIf || []) {
          out.push(`${pad}elif ${pyCond(ei.cond)}:`);
          pushBlock(out, pyStmts(collectChainBodies(ei), indent + 1, prog), pad);
        }
        if (st.else) {
          out.push(`${pad}else:`);
          pushBlock(out, pyStmts(normalizeElse(st.else), indent + 1, prog), pad);
        }
        break;
      }
      case 'blockternary': {
        out.push(`${pad}${pyLhs('_lt')} = (${pyBody(st.then)} if ${pyCond(st.cond)} else ${pyBody(st.elseExpr)})`.replace('_lt = ', '_lt = '));
        out.push(`${pad}pass`);
        break;
      }
      case 'for': {
        const initM = st.init.match(/^([A-Za-z_$][\w$]*)\s*=\s*([\s\S]+)$/);
        if (initM) {
          out.push(`${pad}${safeEmitId(initM[1])} = ${pyExpr(initM[2])}`);
        }
        out.push(`${pad}while ${pyCond(st.cond)}:`);
        const inner = pyStmts(st.body, indent + 1, prog);
        const stepM = st.step.match(/^([A-Za-z_$][\w$]*)\s*(\+\+|--)$/);
        if (stepM) {
          inner.push(`${'    '.repeat(indent + 1)}${safeEmitId(stepM[1])} ${stepM[2] === '++' ? '+' : '-'}= 1`);
        } else if (st.step.trim()) {
          inner.push(`${'    '.repeat(indent + 1)}${pyExpr(st.step)}`);
        }
        pushBlock(out, inner, pad);
        break;
      }
      case 'while':
        out.push(`${pad}while ${pyCond(st.cond)}:`);
        pushBlock(out, pyStmts(st.body, indent + 1, prog), pad);
        break;
      case 'match':
        pyMatch(out, st, indent, prog);
        break;
      default:
        throw new EmitUnsupportedError(`py stmt ${st.type}`);
    }
  }
  return out;
}

function collectChainBodies(ei) {
  return ei.body;
}

function pushBlock(out, inner, pad) {
  out.push(...(inner.length ? inner : [`${pad}    pass`]));
}

function stripThrow(expr) {
  const t = pyExprRaw(expr).trim();
  return t.replace(/^new\s+/, '').replace(/^Error\((.*)\)$/, '$1');
}

function pyCond(cond) {
  return pyExprRaw(cond);
}

function pyStmtRhs(rhs, indent) {
  void indent;
  return pyExprRaw(rhs);
}

function pyStmtTail(expr, indent) {
  void indent;
  return pyExprRaw(expr);
}

function pyBody(blockternaryOrExpr) {
  if (blockternaryOrExpr && blockternaryOrExpr.parts) return pyExprRaw(blockternaryOrExpr);
  return '';
}

function pyLhs(path) {
  return String(path).split('.').map(safeEmitId).join('.');
}

function pyAssignOp(op) {
  switch (op) {
    case '=': return '=';
    case '+=': return '+=';
    case '-=': return '-=';
    case '*=': return '*=';
    case '/=': return '/=';
    case '%=': return '%=';
    case '|=': return '|=';
    case '&=': return '&=';
    case '^=': return '^=';
    case '<<=': return '<<=';
    case '>>=': return '>>=';
    default:
      if (op === '|=') return '|=';
      throw new Error(`LIN_EMIT_PY_OP: ${op}`);
  }
}

export function pyExprRaw(expr) {
  const text = expr && expr.parts
    ? expr.parts.map((p) => (p.kind === 'raw' ? p.text : nodeToJs(p.node))).join(' ')
    : String(expr ?? '');
  return pyExpr(text);
}

function nodeToJs(node) {
  return jsBodyNodeInline(node);
}

function jsBodyNodeInline(node) {
  if (node.kind === 'closure' || node.kind === 'fnlit') return `lambda: None`;
  if (node.kind === 'arrow') return `lambda: None`;
  throw new EmitUnsupportedError(`py inline ${node.kind}`);
}

function templatesToFStrings(s) {
  let guard = 0;
  while (s.includes('`') && guard++ < 50) {
    const start = s.indexOf('\`');
    let i = start + 1;
    let depth = 0;
    let end = -1;
    for (; i < s.length; i++) {
      const c = s[i];
      if (c === '\\') {
        i++;
        continue;
      }
      if (c === '$' && s[i + 1] === '{') {
        depth++;
        i++;
        continue;
      }
      if (c === '}') depth--;
      else if (c === '\`' && depth <= 0) {
        end = i;
        break;
      }
      void depth;
    }
    if (end < 0) break;
    const body = s.slice(start + 1, end);
    const expr = 'f"' + body.replace(/\$\{([^}]*)\}/g, (_, e) => '{' + e.trim() + '}').replace(/"/g, '\\"') + '"';
    s = s.slice(0, start) + expr + s.slice(end + 1);
  }
  return s;
}

export function pyExpr(text) {
  let s = String(text);
  s = templatesToFStrings(s);
  s = s.replace(/JSON\.stringify\(/g, 'json.dumps(');
  s = s.replace(/([A-Za-z_$][\w$]*)\.charCodeAt\(([^()]*)\)/g, '_lia_ord($1[$2])');
  s = s.replace(/([A-Za-z_$][\w$]*)\.length\b/g, '_lia_len($1)');
  s = s.replace(/String\(([A-Za-z_$][\w$]*)\)/g, '_lia_str($1)');
  s = s.replace(/\btypeof\s+([A-Za-z_$][\w$]*(?:\([^()]*\))?)/g, '_lia_typeof($1)');
  s = s.replace(/\bundefined\b/g, 'None').replace(/\bnull\b/g, 'None');
  s = s.replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False');
  s = s.replace(/\bnew\s+Error\(([^()]*)\)/g, 'Exception($1)');
  s = s.replace(/\bMath\.floor\(/g, '_lia_floor(');
  s = s.replace(/\bMath\.abs\(/g, 'abs(');
  s = s.replace(/\bMath\.min\(/g, 'min(');
  s = s.replace(/\bMath\.max\(/g, 'max(');
  s = s.replace(/\bMath\.round\(/g, '_lia_round(');
  s = s.replace(/\bString\(/g, '_lia_str(');
  s = s.replace(/\bNumber\(/g, '_lia_num(');
  s = s.replace(/\bisNaN\(/g, '_lia_isnan(');
  s = s.replace(/\bNumber\.isFinite\(/g, '_lia_isfinite(');
  s = s.replace(/===/g, '==').replace(/!==/g, '!=');
  s = s.replace(/\s*&&\s*/g, ' and ').replace(/\s*\|\|\s*/g, ' or ');
  s = replaceNot(s);
  s = replaceTernariesPy(s);
  return s;
}

function replaceNot(s) {
  let out = '';
  let i = 0;
  while (i < s.length) {
    if (s[i] === '!' && /[A-Za-z_(]/.test(s[i + 1] || '')) {
      out += 'not ';
      i++;
      continue;
    }
    out += s[i];
    i++;
  }
  return out;
}

export function replaceTernariesPy(s) {
  let guard = 0;
  for (;;) {
    if (guard++ > 50) break;
    const t = findTopTernary(s);
    if (!t) break;
    const cond = s.slice(t.condStart, t.qIdx).trim();
    const thenE = s.slice(t.qIdx + 1, t.colonIdx).trim();
    const elseE = s.slice(t.colonIdx + 1, t.end).trim();
    s = s.slice(0, t.condStart) + `(${thenE} if (${cond}) else ${elseE})` + s.slice(t.end);
  }
  return s;
}

function findTopTernary(s) {
  let depth = 0;
  let quote = null;
  let qIdx = -1;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') {
      quote = c;
      continue;
    }
    if ('([{'.includes(c)) depth++;
    else if (')]}'.includes(c)) depth--;
    else if (depth === 0 && c === '?' ) qIdx = i;
    else if (depth === 0 && c === ':' && qIdx >= 0) {
      return { condStart: 0, qIdx, colonIdx: i, end: s.length };
    }
  }
  return null;
}

