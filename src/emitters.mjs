function emitJavaFn(lines, fn) {
  prepareNativeFn(fn);
  if (process.env.DBG2) console.error('JAVA FN', fn.name, 'bodyText:', JSON.stringify(stmtsText(fn).slice(0,60)), 'strP:', [...strParamNames(fn)]);
  const strP = new Set(strParamNames(fn));
  const isBool = retIsBool(fn);
  const ps = paramList(fn);
  for (const p of ps) {
    if (strP.has(p.name)) p.type = '@str';
    else if (!p.type || p.type === 'any') p.type = 'int';
  }
  const sig = ps.map((p) => `${javaType(p.type)} ${safeEmitId(p.name)}`).join(', ');
  let retT = fn.returnType ? fn.returnType.replace(/^[^A-Za-z]+/, '') : null;
  if (!retT && isBool) retT = '@bool';
  const ret = retT ? javaType(retT) : javaType(ps[0] && !strP.has(ps[0].name) ? ps[0].type : 'int');
  lines.push(`  public static ${ret} ${safeEmitId(snakeCase(fn.name))}(${sig}) {`);
  const locals = new Set();
  for (const st of fn.body) collectLocalsGo(st, locals, ps.map((p) => p.name));
  for (const l of locals) {
    const pt = ps.find((p) => p.name === l)?.type || 'int';
    lines.push(`    ${javaType(pt)} ${safeEmitId(l)} = ${javaZero(pt)};`);
  }
  lines.push(javaStmts(fn.body, 2, fn));
  lines.push('  }');
}

function javaIndent(d) {
  return '  '.repeat(d);
}

function javaStmts(stmts, depth, fn) {
  const out = [];
  const pad = javaIndent(depth);
  for (const st of stmts) {
    switch (st.type) {
      case 'return':
        out.push(`${pad}return ${javaExpr(javaRaw(st.expr))};`);
        break;
      case 'throw':
        throw new EmitUnsupportedError('java: throw (use unchecked)');
      case 'break':
        out.push(`${pad}break;`);
        break;
      case 'continue':
        out.push(`${pad}continue;`);
        break;
      case 'assign':
        out.push(`${pad}${safeEmitId(st.idPath)} ${st.op} ${stripDeclKw(javaExpr(javaRaw(st.rhs)))};`);
        break;
      case 'expr':
        out.push(`${pad}${stripDeclKw(javaExpr(javaRaw(st.expr)))};`);
        break;
      case 'if': {
        out.push(`${pad}if (${javaExpr(javaRaw(st.cond))}) {`);
        out.push(javaStmts(st.then, depth + 1, fn));
        for (const ei of st.elseIf || []) {
          out.push(`${pad}} else if (${javaExpr(javaRaw(ei.cond))}) {`);
          out.push(javaStmts(collectChainBodies(ei), depth + 1, fn));
        }
        if (st.else) {
          out.push(`${pad}} else {`);
          out.push(javaStmts(normalizeElse(st.else), depth + 1, fn));
        }
        out.push(`${pad}}`);
        break;
      }
      case 'for': {
        const initM = st.init.match(/^([A-Za-z_$][\w$]*)\s*=\s*([\s\S]+)$/);
        const stepM = st.step.match(/^([A-Za-z_$][\w$]*)\s*(\+\+|--)$/);
        const init = initM ? `long ${initM[1]} = ${javaExpr(initM[2])}` : '';
        const step = stepM ? `${stepM[1]}${stepM[2] === '++' ? '++' : '--'}` : javaExpr(st.step);
        out.push(`${pad}for (${init}; ${javaExpr(javaRaw(st.cond))}; ${step}) {`);
        out.push(javaStmts(st.body, depth + 1, fn));
        out.push(`${pad}}`);
        break;
      }
      case 'while':
        out.push(`${pad}while (${javaExpr(javaRaw(st.cond))}) {`);
        out.push(javaStmts(st.body, depth + 1, fn));
        out.push(`${pad}}`);
        break;
      case 'match': {
        const target = safeEmitId(javaRaw(st.target).trim());
        for (let idx = 0; idx < st.arms.length; idx++) {
          const arm = st.arms[idx];
          const cond = javaArmCond(target, arm.pat, arm.guard);
          if (idx === 0) out.push(`${pad}if (${cond}) {`);
          else out.push(`${pad}} else if (${cond}) {`);
          out.push(javaStmts(arm.body, depth + 1, fn));
        }
        out.push(`${pad}}`);
        break;
      }
      default:
        throw new EmitUnsupportedError(`java stmt ${st.type}`);
    }
  }
  return out.join('\n');
}

function javaArmCond(target, pat, guard) {
  if (pat === '_') return guard ? guard : 'true';
  let base = `${target} == ${pat}`;
  if (guard) base += ` && (${guard})`;
  return base;
}

function javaRaw(expr) {
  return expr && expr.parts
    ? expr.parts.map((p) => (p.kind === 'raw' ? p.text : javaInline(p.node))).join(' ')
    : String(expr ?? '');
}

function javaInline(node) {
  throw new EmitUnsupportedError(`java inline ${node.kind}`);
}

export function javaExpr(text) {
  let s = String(text);
  s = s.replace(/([A-Za-z_$][\w$]*)\.charCodeAt\(([^()]*)\)/g, '(int)($1.charAt((int)($2)))');
  s = s.replace(/([A-Za-z_$][\w$]*)\.length\b(?!\()/g, '$1.length()');
  s = s.replace(/String\(([A-Za-z_$][\w$]*)\)/g, 'String.valueOf($1)');
  s = s.replace(/===/g, '==').replace(/!==/g, '!=');
  s = s.replace(/\btrue\b/g, 'true').replace(/\bfalse\b/g, 'false');
  return s;
}
